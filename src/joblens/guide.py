def _fmt(v: Any) -> str:
    import json

    return "`" + json.dumps(v, ensure_ascii=False) + "`"


def _nested(model: type[BaseModel]) -> list[str]:
    return [
        f"  - `{name}`: {f.description}" for name, f in model.model_fields.items() if f.description
    ]


def render_guide() -> str:
    lines = [
        "# Labelling guide",
        "",
        f"Schema version **{SCHEMA_VERSION}**. Generated by `joblens labeling-guide` from the "
        "field descriptions in `src/joblens/schema.py`: the schema is the single source of "
        "truth, so edit descriptions there and regenerate. The same text instructs the teacher "
        "model and the human reviewer.",
        "",
        "General rules: label only what the posting states; use `unknown`, `not_mentioned`, "
        "`null` or `[]` when it does not say; do not guess from the company or the job family.",
        "",
        "## Fields",
        "",
    ]
    nested: dict[str, type[BaseModel]] = {
        "locations": Location,
        "salary": Salary,
        "languages_required": LanguageRequirement,
    }
    for name, field in JobPosting.model_fields.items():
        lines.append(f"### `{name}`")
        lines.append("")
        lines.append(field.description or "")
        if name in nested:
            lines.append("")
            lines.extend(_nested(nested[name]))
        lines.append("")
    lines += [
        "## Worked examples",
        "",
        "| Posting snippet | Field | Label |",
        "|---|---|---|",
    ]
    for snippet, field_name, value in WORKED_EXAMPLES:
        lines.append(f"| {snippet} | `{field_name}` | {_fmt(value)} |")
    lines += [
        "",
        "Salary annualisation (used by the metrics, not stored in labels): "
        "month × 12, hour × 2,080 (40 h × 52 weeks).",
        "",
        "## Full examples",
        "",
    ]
    for title, text, label in FEW_SHOT:
        lines += [
            f"**{title}**",
            "",
            "```text",
            text,
            "```",
            "",
            "```json",
            answer_json(label),
            "```",
            "",
        ]
    return "\n".join(lines).rstrip() + "\n"


def write_guide(path: Path) -> Path:
    path.write_text(render_guide(), encoding="utf-8")
    return path
